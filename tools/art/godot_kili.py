"""
Copies the Expo game's painted art into the Godot project for the strategy
screen and the Lava Tower and summit night climbs. All of it is
project-owned, generated by the scripts in tools/art. (The rock inside the
climbs is tools/art/godot_backwalls.py.)

    python3 tools/art/godot_kili.py
"""

import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
HD = ROOT / "assets" / "hd2d"
OUT = ROOT / "godot" / "assets"


def main():
    scenery = OUT / "scenery"
    for name in ["lava-foreground", "plateau", "summit-foreground", "summit-sea"]:
        shutil.copyfile(HD / "scenery" / f"{name}.png", scenery / f"{name}.png")
    world = OUT / "world"
    world.mkdir(exist_ok=True)
    for zone in ["rainforest", "moorland", "desert", "snow"]:
        shutil.copyfile(HD / "world" / f"{zone}.webp", world / f"{zone}.webp")
        shutil.copyfile(HD / "world" / f"{zone}.json", world / f"{zone}.json")
    # The camp's fog is the climbs' fog (assets/scenery/fog.png): one copy
    # in the APK.
    for name in ["map.png", "props.png"]:
        shutil.copyfile(HD / "world" / name, world / name)
    for who in ["you", "lena", "marco", "jun"]:
        shutil.copyfile(HD / "characters" / f"{who}-map.png", world / f"{who}-map.png")
    print("copied scenery and world art into", OUT)


if __name__ == "__main__":
    main()
